/** Everything language-dependent the demo needs. Prices are in grosze. */
export function demoLocale(lang: Language) {
  const locale = LOCALE[lang];
  // `useGrouping: "always"`: some locales group only from 5 digits by default.
  const decimal = new Intl.NumberFormat(locale, { maximumFractionDigits: 1, useGrouping: "always" });
  const currency = (digits: number) =>
    new Intl.NumberFormat(locale, {
      style: "currency",
      currency: "PLN",
      minimumFractionDigits: digits,
      maximumFractionDigits: digits,
      useGrouping: "always",
    });
  const rounded = currency(0);
  const exact = currency(2);

  return {
    t: TEXT[lang],
    formatNumber: (value: number) => decimal.format(value),
    formatPrice: (grosze: number) => rounded.format(grosze / 100),
    formatPln: (grosze: number) => exact.format(grosze / 100),
    formatDate: (time: number) => new Date(time).toLocaleDateString(locale),
    componentName: (c: CatalogComponent) => (lang === "pl" ? c.name : (NAMES[lang][c.code] ?? c.name)),
    /** Drawings carry text, so EN and DE have their own copies. */
    layerUrl: (url: string) =>
      lang === "pl" ? url : url.replace("/camperiada/layers/", `/camperiada/layers/${lang}/`),
  };
}
